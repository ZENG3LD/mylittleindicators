    #[test]
    fn weight_barometer_assembles_from_structure() {
        let ema = weight_of(IndicatorId::Ema).unwrap();
        let sma = weight_of(IndicatorId::Sma).unwrap();
        let lr = weight_of(IndicatorId::Lr).unwrap();
        // EMA keeps no window store; SMA holds a Vec window (running sum, O(1)); LR holds
        // the window AND rescans it (O(period) -> Linear class). Weight is assembled from
        // those declared stores + update class, never hand-tagged, and is PERIOD-FREE.
        assert!(ema < sma, "no-buffer EMA ({ema}) < Vec-buffer SMA ({sma})");
        assert!(sma < lr, "running-sum SMA ({sma}) < per-bar-rescan LR ({lr})");
        assert!((0.0..1.0).contains(&lr));

        // A budget between SMA and LR admits the cheap MAs and prunes the rescan LR.
        let budget = (sma + lr) / 2.0;
        let admitted: Vec<_> = family_members(Family::MovingAverage)
            .into_iter()
            .filter(|id| weight_of(*id).unwrap_or(1.0) <= budget)
            .collect();
        assert!(admitted.contains(&IndicatorId::Ema), "cheap EMA admitted under budget");
        assert!(!admitted.contains(&IndicatorId::Lr), "heavy LR pruned by the cost budget");

        // Any still-unfilled id has no weight (dynamic sentinel).
        if let Some(u) = IndicatorId::all().find(|id| !is_contract_backed(*id)) {
            assert_eq!(weight_of(u), None, "{u:?}: uncontracted id must have no weight");
        }
    }

