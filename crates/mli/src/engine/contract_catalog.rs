//! `ContractCatalog` — the `id -> contract` metadata projection (sibling of the
//! `ContractFactory` construction path). Take an id, get its static contract
//! facets (family / inputs / output / cost / outputs / source / slots / volume)
//! WITHOUT building an instance — the path the optimizer prices + prunes config
//! trees with. The catalog IS the contract set viewed by id.
//!
//! Makes families **pluggable from self-declaration**: `family_members(Channel)`
//! asks each id's contract for its `FAMILY`, not a stringly catalog table.
//!
//! The per-id projections (`family_of` … `needs_volume_of`) are GENERATED by
//! `contract_universe!` in `contract_engine` from the ONE member list — the SAME
//! list that generates `ContractFactory`, so the two frontiers cannot drift — and
//! re-exported here. The derived functions below (weights, `family_members`) are
//! hand-written logic over those generated projections.

use crate::engine::contract_engine::IndicatorOutputId;
use crate::engine::indicator_id::IndicatorId;
use crate::contract::{Family, WEIGHTS};
use crate::engine::stream_kind::StreamKind;

// The per-id metadata projections (`family_of` … `needs_volume_of`) are GENERATED
// by `contract_universe!` in `contract_engine` from the ONE member list — the SAME
// list that generates `ContractFactory`, so the two frontiers cannot drift. They
// are re-exported here so `contract_catalog::family_of` (and the rest) stay stable
// import paths, and so the derived logic below reads them by their short names.
pub use crate::engine::contract_engine::{
    cost_of, family_of, inputs_of, needs_time_of, needs_volume_of, output_ids_of, outputs_of,
    slot_default_members_of, slots_of, source_of,
};

/// `true` if `id` is contract-backed (has a self-declared contract). The
/// coverage frontier — grows toward 556 as ids are filled.
pub fn is_contract_backed(id: IndicatorId) -> bool {
    family_of(id).is_some()
}

/// Every id that self-declares membership in `family`. Derived from the
/// contracts, not from a catalog table. Currently ranges over the
/// contract-backed ids only.
pub fn family_members(family: Family) -> Vec<IndicatorId> {
    IndicatorId::all()
        .filter(|id| family_of(*id).map_or(false, |fs| fs.contains(&family)))
        .collect()
}

/// The coordinate system ([`crate::contract::ValueDomain`]) of one of `id`'s outputs —
/// the per-output semantic both strategies (comparability) and render (pane/scale)
/// consume. `None` if `id` is not contract-backed or does not emit `output`.
pub fn output_domain(
    id: IndicatorId,
    output: IndicatorOutputId,
) -> Option<crate::contract::ValueDomain> {
    outputs_of(id)?.iter().find(|o| o.id == output).map(|o| o.domain)
}

/// Every named output the contract exposes in `domain` — the strategy layer's candidate
/// pool for one comparability class, read STRAIGHT from the self-describing contract
/// (`IndicatorId::all()` × `output_ids_of` × `output_domain`). No separate catalog: the
/// contract IS the capability menu (moved from `mli-strategies::generator`, taxonomy
/// 2026-07-03 — the pools are a contract-catalog projection, not a strategy-side shim).
pub fn outputs_in_domain(domain: crate::contract::ValueDomain) -> Vec<IndicatorOutputId> {
    IndicatorId::all()
        .flat_map(|id| output_ids_of(id).iter().copied().map(move |oid| (id, oid)))
        .filter(move |(id, oid)| output_domain(*id, *oid) == Some(domain))
        .map(|(_, oid)| oid)
        .collect()
}

/// Every domain that holds ≥2 named outputs — the crossable comparability classes the
/// strategy layer enumerates over. Built straight from the self-describing contract.
/// Domains with <2 outputs are absent (nothing to cross). `Discrete` is excluded:
/// categorical outputs compared by equality cannot be meaningfully crossed as continuous
/// signals. Moved from `mli-strategies::generator` (taxonomy 2026-07-03).
pub fn crossable_pools() -> Vec<(crate::contract::ValueDomain, Vec<IndicatorOutputId>)> {
    use crate::contract::ValueDomain::{Centered, Count, Flow, Magnitude, Ordinal, Percent, Price, Ratio};
    [Price, Magnitude, Percent, Centered, Count, Ratio, Flow, Ordinal]
        .into_iter()
        .filter_map(|d| {
            let pool = outputs_in_domain(d);
            if pool.len() >= 2 { Some((d, pool)) } else { None }
        })
        .collect()
}


/// Rough per-event input cost of a stream — an order book (N levels) ≫ a bar
/// (OHLCV) ≫ a tick. Derived from the declared `INPUT`, not per indicator.
fn stream_cost(s: StreamKind) -> f64 {
    match s {
        StreamKind::OrderBook => 8.0,
        StreamKind::Bar => 1.0,
        _ => 0.5,
    }
}

/// Total input cost of `id` from its declared `INPUT` streams.
fn input_cost(id: IndicatorId) -> f64 {
    inputs_of(id).map_or(0.0, |ins| ins.iter().copied().map(stream_cost).sum())
}

/// Sum of the MARGINAL costs of `id`'s outputs — restricted to the ids in `consumed`
/// (or every port when `consumed` is `None`). The shared base is NOT here (it lives in
/// `local_cost`); this is only what the taken outputs add on top. Value/byproduct
/// outputs are `FREE` → 0.
fn outputs_marginal(id: IndicatorId, consumed: Option<&[IndicatorOutputId]>) -> f64 {
    outputs_of(id).map_or(0.0, |ps| {
        ps.iter()
            .filter(|p| consumed.map_or(true, |sel| sel.contains(&p.id)))
            .map(|p| p.cost.marginal_cost())
            .sum()
    })
}

/// Raw (unbounded) cost of `id` when `consumed` outputs are taken (`None` = the full
/// surface): shared base (`local_cost`) + Σ marginal of taken outputs + input stream
/// cost + recursive edge cost. Each inner [`Port`] charges its producer's base + the
/// marginals of just the outputs that edge wires — so a node that pulls only a cheap
/// port is weighed cheaply. PERIOD-FREE (structure only). `None` if not contract-backed.
fn raw_cost_of(id: IndicatorId, consumed: Option<&[IndicatorOutputId]>) -> Option<f64> {
    let cost = cost_of(id)?;
    let edges: f64 = cost
        .inner
        .iter()
        .filter_map(|e| raw_cost_of(e.producer, Some(e.outputs)))
        .sum();
    // Each slot reduces to the same recursive consumed-port cost as an edge; the
    // STATIC-weight member is the indicator's own default, read off its typed
    // `defaults()` (`slot_default_members_of`) — no separate `Slot.default` field.
    // A slot charges the member's base + inputs + edges only (no marginal on top,
    // since it consumes the primary FREE output).
    let slots: f64 = slots_of(id)
        .iter()
        .zip(slot_default_members_of(id).iter().copied())
        .filter_map(|(_s, m)| raw_cost_of(m, Some(&[])))
        .sum();
    Some(cost.local_cost() + outputs_marginal(id, consumed) + input_cost(id) + edges + slots)
}

/// The normalized weight in `[0, 1)` of `id` consuming its FULL surface (base + every
/// port's marginal + recursive edges), saturated. PERIOD-FREE — it ranks by structure
/// (store class, update class, recursive ports/members), not by the chosen period.
/// `None` if not contract-backed. For a consumer that wires only some outputs, use
/// [`weight_consumed`] — the honest, port-attributed pruning signal.
pub fn weight_of(id: IndicatorId) -> Option<f64> {
    let raw = raw_cost_of(id, None)?;
    Some(raw / (raw + WEIGHTS.norm_k))
}

/// The normalized weight in `[0, 1)` of consuming only `outputs` of `id` (period-free):
/// `base + Σ marginal(outputs)` + recursive edges, saturated. A consumer
/// wiring just the cheap primary output of a rich producer pays the base only — not
/// its heavy analytics. This is the machine-pruning signal for port-selective
/// edges. `None` if not contract-backed.
pub fn weight_consumed(id: IndicatorId, outputs: &[IndicatorOutputId]) -> Option<f64> {
    let raw = raw_cost_of(id, Some(outputs))?;
    Some(raw / (raw + WEIGHTS.norm_k))
}

/// The `[min, max]` weight of `id` over ALL admissible fillings of its
/// own slots. A slot member is config-chosen and each candidate weighs differently,
/// so the consumer's weight is a RANGE, not a point — `min` uses the lightest
/// candidate of each slot, `max` the heaviest (over the slot's TYPED candidate set,
/// `Slot.candidates`); the
/// `default`-resolved [`weight_of`] sits inside. With no slots the range collapses
/// to a single point. The pruning use: a search sweeps the slot as a dimension, or
/// drops the indicator when even `min` exceeds the budget. `None` if not
/// contract-backed.
pub fn weight_range(id: IndicatorId) -> Option<(f64, f64)> {
    let (lo, hi) = raw_cost_range(id)?;
    let sat = |r: f64| r / (r + WEIGHTS.norm_k);
    Some((sat(lo), sat(hi)))
}

/// The additive (un-normalized) `[min, max]` cost-points of `id` at `period` over ALL
/// admissible slot fillings: `base` (everything EXCEPT this id's own slots, recomputed
/// once) + per slot the lightest / heaviest candidate's recursive cost. The summable
/// budget-currency form behind [`weight_range`] (saturating it gives the normalized
/// range) and [`cost_points_range`]. `None` if not contract-backed.
fn raw_cost_range(id: IndicatorId) -> Option<(f64, f64)> {
    let cost = cost_of(id)?;
    // Base = everything except this id's own slots (recomputed once).
    let edges: f64 = cost
        .inner
        .iter()
        .filter_map(|e| raw_cost_of(e.producer, Some(e.outputs)))
        .sum();
    let base = cost.local_cost() + outputs_marginal(id, None) + input_cost(id) + edges;
    let (mut lo, mut hi) = (base, base);
    for s in slots_of(id) {
        // Candidates are the TYPED admissible set — the `#[slot]` field's
        // `FamilyId::MEMBERS` (e.g. `SmootherId::MEMBERS` = the smoother-safe MAs).
        // The compiler already confined the field to these, so there is no family
        // lookup, no volume filter, no weight cap; the range spans the full typed set.
        // Slots charge base + inputs + edges of each candidate (no marginal, primary FREE).
        let costs: Vec<f64> = s
            .candidates
            .iter()
            .copied()
            .filter_map(|m| raw_cost_of(m, Some(&[])))
            .collect();
        if costs.is_empty() {
            continue;
        }
        lo += costs.iter().copied().fold(f64::INFINITY, f64::min);
        hi += costs.iter().copied().fold(f64::NEG_INFINITY, f64::max);
    }
    Some((lo, hi))
}

// The bag-cost path (`inner_for` / `raw_cost_bagged` / `weight_from_bag` /
// `cost_points_from_bag`) was REMOVED in the bag cut-over. Order-time cost that
// followed the bag's nested config + chosen smoother is gone with the bag; the
// typed cost path (`weight_of` / `weight_range` / `cost_points*`) over static
// default members survives below.

// ─────────────────────────────────────────────────────────────────────────────
// Cost-points — the ADDITIVE budget currency.
//
// `weight_*` return the saturated `[0, 1)` pruning/ranking signal — per-member and
// NON-additive (`raw / (raw + norm_k)`). A budget assembler ("build every strategy
// combination whose TOTAL cost fits N points") needs SUMMABLE units: the functions
// below return the raw, recursively-assembled cost-points BEFORE the saturation. Sum
// them across a strategy's indicators and compare to the budget; the saturated weight
// stays the per-member ranking/pruning signal.
//
// The coefficients (`crate::contract::WEIGHTS`) are a v1 rubric — correct ORDERING by
// structural class (PERIOD-FREE), not measured ns. An empirical calibration wave refits
// them to microbenchmarked per-update time on the target box, so the absolute point
// SCALE is calibration-dependent; the SHAPE (additive, recursive, structural) is stable. See
// `nemo/docs/mli-contract/architecture/contract-dependency-model.md` (cost-points +
// deferred calibration).
// ─────────────────────────────────────────────────────────────────────────────

/// Additive cost-points of `id` consuming its FULL surface (base + every
/// port marginal + recursive edges + default-resolved slots). The summable
/// budget-currency twin of [`weight_of`]. `None` if not contract-backed.
pub fn cost_points(id: IndicatorId) -> Option<f64> {
    // Under `calibrated`: the measured flat ns (already includes nested cost) REPLACES the
    // structural prior wholesale. Feature off → `measured_cost` is `None`, pure prior.
    if let Some(measured) = crate::engine::calibration_shim::measured_cost(id) {
        return Some(measured);
    }
    raw_cost_of(id, None)
}

/// Additive cost-points of consuming only `outputs` of `id` (period-free) — the
/// port-selective budget twin of [`weight_consumed`]. A consumer wiring just the cheap
/// primary output pays the base, not the heavy analytics. `None` if not contract-backed.
pub fn cost_points_consumed(id: IndicatorId, outputs: &[IndicatorOutputId]) -> Option<f64> {
    let raw = raw_cost_of(id, Some(outputs))?;
    // Under `calibrated`: the bench measures the WHOLE indicator, not per-output. Scale the
    // measured flat total by the prior's port-fraction so the selective signal survives (a
    // consumer wiring only the cheap primary still pays less than the full surface).
    if let Some(measured_full) = crate::engine::calibration_shim::measured_cost(id) {
        let raw_full = raw_cost_of(id, None)?;
        if raw_full > 0.0 {
            return Some(measured_full * (raw / raw_full));
        }
    }
    Some(raw)
}

/// Additive `[min, max]` cost-points of `id` over ALL admissible slot
/// fillings — the summable budget twin of [`weight_range`]. The assembler sweeps the
/// slot as a search dimension and prices each end; with no slots the range collapses to
/// a point. `None` if not contract-backed.
pub fn cost_points_range(id: IndicatorId) -> Option<(f64, f64)> {
    let (lo, hi) = raw_cost_range(id)?;
    // Under `calibrated`: scale the prior's slot-fill range by the measured/prior ratio so the
    // range is expressed in the same measured-ns currency as `cost_points`.
    if let Some(measured_full) = crate::engine::calibration_shim::measured_cost(id) {
        let raw_full = raw_cost_of(id, None)?;
        if raw_full > 0.0 {
            let k = measured_full / raw_full;
            return Some((lo * k, hi * k));
        }
    }
    Some((lo, hi))
}

// ─────────────────────────────────────────────────────────────────────────────
// Per-config warmup cost (C3, cost-layer1-closure-plan-2026-07-02, design D1).
//
// `cost_points`/`cost_points_range` above are PERIOD-FREE (structural) or, under
// `calibrated`, priced from `MEASURED_NS` — ONE row per indicator at its DEFAULT
// config. Neither has any notion of `config_hash`. The functions below are the
// per-SWEPT-config complement: keyed by the exact `(id, config_hash)` identity a
// warmup `ColumnKey` dedups by, sourced from `mlq-warmup`'s opt-in real-sweep
// harvest (`MEASURED_NS_PER_CONFIG`). Honest-Err doctrine (plan §0.7): the source
// of a returned cost is ALWAYS explicit — never a silent structural substitution.
// ─────────────────────────────────────────────────────────────────────────────

/// Which table produced a per-config cost estimate — never silently conflated.
#[derive(Debug, Clone, Copy, PartialEq)]
pub enum CostSource {
    /// This exact `(id, config_hash)` was harvested from a real warmup sweep
    /// (`MEASURED_NS_PER_CONFIG`, `calibrated` feature only).
    MeasuredConfig,
    /// No harvested entry for this exact config — fell back to the period-free
    /// structural `cost_points(id)` rubric (or, under `calibrated`, `MEASURED_NS`'s
    /// per-DEFAULT-config figure, whichever `cost_points` itself resolves to).
    /// Marked explicitly so a caller can distinguish "measured at this config"
    /// from "structural estimate" — the honest-uncalibrated marker the plan
    /// requires (never a silent fallback dressed up as a measurement).
    StructuralFallback,
}

/// Additive cost-points of `id` AT `config_hash` — the per-config twin of
/// [`cost_points`]. Returns `(points, source)` so the caller always knows whether
/// `points` came from a real per-config harvest or the structural fallback.
/// `None` if `id` is not contract-backed at all (same as every other function
/// here — an uncontracted id has no cost model of any kind).
pub fn cost_points_for_config(id: IndicatorId, config_hash: u64) -> Option<(f64, CostSource)> {
    if let Some(measured) = crate::engine::calibration_shim::measured_cost_for_config(id, config_hash) {
        return Some((measured, CostSource::MeasuredConfig));
    }
    cost_points(id).map(|points| (points, CostSource::StructuralFallback))
}

/// Measured warmup MEMORY weight of `id`, in MB (revived `MemWeight`, 07-01
/// costometer plan Ф3a — heap-live bytes + inline core size at the indicator's
/// DEFAULT config's warmup depth). `None` when the `calibrated` feature is off or
/// `id` has no baked measurement (e.g. not contract-backed, or not yet calibrated).
/// Unlike [`cost_points_for_config`] there is no structural fallback here: memory
/// is not modeled structurally anywhere in this crate, so an absent measurement is
/// honestly `None`, not a made-up number.
pub fn mem_points(id: IndicatorId) -> Option<f64> {
    crate::engine::calibration_shim::measured_mem(id)
}

