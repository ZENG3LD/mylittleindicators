    #[test]
    fn machine_defaults_pass_own_valid_params_universe() {
        // The permanent invariant this test guards: ANY contract-backed indicator's
        // `machine_defaults()` order must build via the SAME gate every real consumer
        // goes through — `IndicatorOrder::build_solo`, which runs `Config::valid_params`
        // on the RAW (possibly still-`Many`) config. `Param::resolved()` on a `Many` axis
        // picks its FIRST value (the min corner) — so this is exactly the point a
        // dual-period indicator's own ordering rule (fast < slow) must not reject.
        //
        // `mli-strategies::enumerate::leaf_for` builds every machine-generator production
        // (zscore_cross / slope_sign / osc_threshold / …) straight off `from_machine_defaults`
        // without ever iterating the cube first — so a `machine_defaults()` whose first point
        // fails `valid_params` silently kills that indicator's whole strategy batch via `?`.
        // Was found doing so for VoVr / Ama / Kvo / Logicsign (2026-07-03); this test is the
        // permanent regression gate for the whole universe, not just those four.
        use crate::engine::contract_engine::IndicatorOrder;

        let mut offenders: Vec<String> = Vec::new();
        for id in IndicatorId::all() {
            let Some(order) = IndicatorOrder::from_machine_defaults(id) else {
                continue; // not contract-backed — no machine_defaults to check
            };
            if let Err(reason) = order.build_solo() {
                offenders.push(format!("{id:?}: {reason:?}"));
            }
        }
        assert!(
            offenders.is_empty(),
            "machine_defaults() must pass its own valid_params for every contract-backed \
             indicator (min-corner build via build_solo, the real consumer path); offenders:\n{}",
            offenders.join("\n")
        );
    }

    /// Deterministic zigzag OHLCV bars — same generator shape as `Ewa`'s test fixture
    /// (`indicators::regime::ewa::tests::zigzag_bars`), reused here so the whole
    /// universe warms up on a realistic price structure (swing pivots, non-degenerate
    /// deltas) rather than a flat or monotonic series that would mask division-by-zero
    /// bugs at small periods.
    fn zigzag_bars(n: usize) -> Vec<(f64, f64, f64, f64, f64)> {
        let mut bars = Vec::with_capacity(n);
        let mut price = 100.0_f64;
        for i in 0..n {
            let next = if i % 2 == 0 { price * 1.03 } else { price * 0.98 };
            let (open, close) = (price, next);
            let high = open.max(close) * 1.002;
            let low = open.min(close) * 0.998;
            bars.push((open, high, low, close, 1000.0));
            price = next;
        }
        bars
    }

    /// A1 2026-07-04 gate: the runtime twin of `machine_defaults_pass_own_valid_params_universe`.
    /// That test only proves the min-corner config BUILDS (`valid_params` + `create` succeed);
    /// it says nothing about what happens once the built core actually RUNS at period=1 —
    /// a rolling std/variance/MAD window of width 1 (or 0 after a `period - 1` sizing) is a
    /// classic division-by-zero / NaN trap that only shows up on real feed, not on construction.
    ///
    /// For every contract-backed `IndicatorId`, build its `machine_defaults()` min corner via
    /// `build_solo()` (same real-consumer gate), feed it 512 deterministic zigzag bars (the
    /// `Ewa` fixture shape), and after every feed assert every SCALAR output (`read`, `grid`
    /// returns `None` for these — the table surface has its own shape and is checked
    /// separately) is finite. Table outputs are read via `grid` and merely asserted `Some`
    /// once the core reports ready — a table's cell-level finiteness is out of scope here.
    ///
    /// `Bar`-only: indicators whose `INPUT` does not include `StreamKind::Bar` never see this
    /// feed and would sit permanently not-ready — irrelevant noise for a PERIOD-floor policy
    /// change, so they are skipped rather than asserted on a feed they cannot consume.
    ///
    /// A single indicator's PANIC (an unguarded `assert!`/index/arithmetic bug inside the
    /// core) must not abort the whole sweep — `catch_unwind` collects it as an offender like
    /// any other failure so one bad core doesn't hide the rest of the universe's report.
    ///
    /// `HalfLifeMr` is EXEMPT from the finite check (NaN still bans it): its own doc
    /// (`hl = -ln(2)/ln(phi)`) defines `f64::INFINITY` as the honest "no mean-reversion
    /// detected" sentinel when the fitted AR(1) `phi` falls outside `(0, 1)` — exactly what
    /// this fixture's near-perfectly anti-persistent zigzag alternation (φ < 0) produces at
    /// ANY window size (its `window` is internally clamped `.max(20)`, so this is a data-shape
    /// artifact, not a period-floor bug). Asserting finiteness there would fail a documented
    /// domain value, not catch a real one.
    #[test]
    fn machine_defaults_min_corner_runtime_smoke() {
        use crate::contract::MarketSample;
        use crate::engine::contract_engine::IndicatorOrder;

        let bars = zigzag_bars(512);
        let mut covered = 0usize;
        let mut offenders: Vec<String> = Vec::new();

        // Suppress the default panic-to-stderr printer while probing — offenders are
        // reported through the assertion message, not console noise from `catch_unwind`.
        let default_hook = std::panic::take_hook();
        std::panic::set_hook(Box::new(|_| {}));

        for id in IndicatorId::all() {
            let Some(inputs) = inputs_of(id) else {
                continue; // not contract-backed
            };
            if !inputs.contains(&StreamKind::Bar) {
                continue; // this feed cannot reach it — out of scope for this smoke
            }
            let Some(order) = IndicatorOrder::from_machine_defaults(id) else {
                continue;
            };
            covered += 1;

            let result = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {
                let mut factory = order.build_solo().map_err(|e| format!("build_solo: {e:?}"))?;
                for &(o, h, l, c, v) in &bars {
                    factory.feed(0, MarketSample::Bar { open: o, high: h, low: l, close: c, volume: v });
                    if !factory.is_ready() {
                        continue;
                    }
                    for out in output_ids_of(id) {
                        if let Some(grid) = factory.grid(*out) {
                            if grid.rows() == 0 {
                                return Err(format!("{out:?}: ready table output has zero rows"));
                            }
                            continue;
                        }
                        let v = factory.read(*out);
                        if v.is_nan() {
                            return Err(format!("{out:?}: NaN after ready"));
                        }
                        if v.is_infinite() && id != crate::engine::indicator_id::IndicatorId::HalfLifeMr {
                            return Err(format!("{out:?}: non-finite value {v} after ready"));
                        }
                    }
                }
                Ok(())
            }));

            match result {
                Ok(Ok(())) => {}
                Ok(Err(reason)) => offenders.push(format!("{id:?}: {reason}")),
                Err(panic) => {
                    let msg = panic
                        .downcast_ref::<&str>()
                        .map(|s| s.to_string())
                        .or_else(|| panic.downcast_ref::<String>().cloned())
                        .unwrap_or_else(|| "<non-string panic payload>".to_string());
                    offenders.push(format!("{id:?}: PANIC: {msg}"));
                }
            }
        }

        std::panic::set_hook(default_hook);

        assert!(covered > 0, "no Bar-consuming contract-backed indicator was probed — harness broken");
        assert!(
            offenders.is_empty(),
            "machine_defaults() min-corner must run cleanly to finite outputs over 512 \
             zigzag bars for every Bar-consuming contract-backed indicator ({covered} covered); \
             offenders:\n{}",
            offenders.join("\n")
        );
    }

